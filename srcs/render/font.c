// A character outside the printable range draws as '?', so a bad string shows instead of vanishing.
const unsigned char	*font_glyph(char character)
{
	int	index = (int)(unsigned char)character - FONT_FIRST_CHAR;

	if (index < 0 || index >= FONT_GLYPH_COUNT)
		index = (int)'?' - FONT_FIRST_CHAR;
	return (g_glyphs[index]);
}
