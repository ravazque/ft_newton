/* Rows of the glyph for 'c'; anything outside the printable range draws as a
 * box, which makes a bad string visible instead of silently empty. */
const unsigned char	*font_glyph(char c)
{
	int	index = (int)(unsigned char)c - FONT_FIRST_CHAR;

	if (index < 0 || index >= FONT_GLYPH_COUNT)
		index = (int)'?' - FONT_FIRST_CHAR;
	return (g_glyphs[index]);
}
